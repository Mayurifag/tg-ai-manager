// Derive Twemoji parser keys from the actual Apple asset filenames.
// Usage: node scripts/generate-emoji-map.cjs [--check]
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const assetsDir = path.join(root, "static/emoji/apple");
const output = path.join(root, "static/js/apple-emoji-map.js");
const parser = {};
vm.createContext(parser);
vm.runInContext(fs.readFileSync(path.join(root, "static/libs/twemoji/twemoji.min.js"), "utf8"), parser);

const mapping = {};
for (const filename of fs.readdirSync(assetsDir).sort()) {
  if (!filename.endsWith(".png")) continue;
  const stem = filename.slice(0, -4);
  if (!/^[0-9a-f]{1,6}(?:-[0-9a-f]{1,6})*$/.test(stem)) {
    throw new Error(`Unexpected emoji asset name: ${filename}`);
  }
  const emoji = String.fromCodePoint(...stem.split("-").map((part) => parseInt(part, 16)));
  const keys = [];
  const parsed = parser.twemoji.parse(emoji, {
    callback(key) { keys.push(key); return "local-asset"; },
  });
  // Skip files the bundled parser cannot represent as exactly one emoji.
  if (keys.length !== 1 || !/^<img [^>]*\/>$/.test(parsed)) continue;
  if (Object.hasOwn(mapping, keys[0])) {
    throw new Error(`Ambiguous emoji key ${keys[0]}: ${mapping[keys[0]]}, ${filename}`);
  }
  mapping[keys[0]] = filename;
}

const sorted = Object.fromEntries(Object.entries(mapping).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
const generated = "// Generated by scripts/generate-emoji-map.cjs; do not edit.\n" +
  "window.TG_APPLE_EMOJI_ASSETS = " + JSON.stringify(sorted) + ";\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== generated) {
    throw new Error("Apple emoji map is stale; run node scripts/generate-emoji-map.cjs");
  }
} else {
  fs.writeFileSync(output, generated);
}
